#!/bin/bash

# Navigate to the directory where the script is located
cd "$(dirname "$0")" || exit

# Initialize or clear the color.txt file
> color.txt

echo "Step 1: Converting, resizing, and stripping metadata..."
# Convert jpg, png, and webp files to webp, resize them, and put them in the parent directory
for ext in jpg png webp; do
  # Check if files with this extension exist
  if ls *.$ext 1> /dev/null 2>&1; then
    magick mogrify -format webp -path ../ -resize "1000x1000>" -strip *.$ext
  fi
done

echo "Step 2: Extracting backgrounds and logging colors..."
# Loop through the original files to only process their corresponding generated webp files
for orig_img in *.{jpg,png,webp}; do
  # Skip if the glob didn't match anything
  [ -e "$orig_img" ] || continue
  
  # Determine the target webp file generated by mogrify in the parent directory
  name="${orig_img%.*}"
  img="../${name}.webp"
  
  # Ensure the generated file exists
  [ -e "$img" ] || continue
  
  basename=$(basename "$img")
  
  # Extract the background color from the top-left pixel
  hex=$(magick "$img" -format "%[hex:p{0,0}]" info:)
  echo "$basename: #$hex" >> color.txt
  
  # Apply the custom 25%
  fuzz="25%"

  # Remove the background, smooth the alpha edge, and trim
  magick "$img" -fuzz $fuzz -fill none -draw "alpha 0,0 floodfill" \
    -channel A -blur 0x2 -level 50%,50% +channel \
    -trim +repage "$img"
    
  echo "Extracted object for $basename (Color: #$hex)"
done

echo "Done! Background colors have been saved to color.txt."
